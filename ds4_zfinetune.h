/* =========================================================================
 * ds4_zfinetune -- 微调侧车: 第三个文件, 自己的权重, 与 zchain 一起挂
 * =========================================================================
 *
 * ★三文件部署(2026-09-08 用户定案)★
 *   ① 量化 GGUF        权重本体(VQ 码 + 骨架)
 *   ② zchain (DQZ2)    反修放大器 —— 把量化掉的原始能力还原回来。★冻结★
 *   ③ finetune (DQZ2)  微调 —— 复盘学到的新行为。每晚可换, 换错删掉即回到 ②。
 *
 * 为什么不是"每晚重解 zchain": 那要从裸量化态起, 重建锚、重跑 43 层, 两小时起,
 * 而且一旦解坏, 还原能力跟着坏 —— 把"学新东西"和"别忘老本事"绑死在一个产物里。
 * 分成两个文件后, ② 永不动, ③ 每晚独立解、独立判、独立回滚。
 *
 * 数学上两者都是 routed 上的加性低秩项, 所以运行时不需要跑两遍:
 *     routed += U₂·diag(z₂)·V₂ᵀx  +  U₃·diag(z₃)·V₃ᵀx
 *             = [U₂|U₃]·diag([z₂;z₃])·[V₂|V₃]ᵀx
 * 装载时按秩拼接成一个 rank(k₂+k₃) 的 z^L, 之后 GPU 上传/kernel/host apply
 * 全部零改动 —— 它们只看见"一个更宽的 z"。秩上限 DS4_AMP_ZK_MAX=1024, 冠军
 * k₂=64, 微调 k₃ 取十几到几十, 离上限很远。
 *
 * ★夹持(trust region)语义变化, 已知并接受★: 拼接后两段共用一个 clip
 * (‖Δ‖≤tr·‖routed‖ 对合并后的 Δ 算一次), tr 取两者较小值。微调 Δ 远小于
 * 还原 Δ 时 clip 恒为 1, 与拼接前逐字同; 若微调 Δ 大到触发夹持, 说明它已经
 * 在改写模型主行为, 那时该停下来看解算, 不该让它悄悄生效。 */
#ifndef DS4_ZFINETUNE_H
#define DS4_ZFINETUNE_H

#include "ds4_zchain.h"

/* 把 add 里的加性 z^L 按秩拼进 base(逐层)。base 的其余记录(GE/λ/RTE/4L)一概不动。
 *
 * 规则(任一不满足即失败, 不做静默降级 —— 侧车是显式请求, 兜底会出假对照):
 *   - 两边层数一致;
 *   - add 的层要么没有 z^L(该层不微调), 要么是加性线性 z(zmul==0 且 zdin==d_model);
 *   - base 该层若已有 z^L, 也必须是加性线性 z(乘性 AMP/AMPD 与加性无法合并);
 *   - 拼接后的秩 ≤ DS4_AMP_ZK_MAX。
 *
 * 成功返回拼进去的层数(0 = add 是空链, 也算失败); 失败返回 -1 并打印原因。
 * base 被就地改写: 受影响层的 zlm 改指向本模块新分配的 fp16 缓冲(不再别名
 * mmap), zmod 重建为合并后的 f32; 这些缓冲随 base 一起活到 ds4_zchain_free。 */
int ds4_zfinetune_merge(ds4_zchain *base, const ds4_zchain *add);

#endif /* DS4_ZFINETUNE_H */
